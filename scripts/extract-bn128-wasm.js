/**
 * Script to extract the pre-compiled bn128 WASM bytecode
 * This generates a .wasm file that can be bundled with Cloudflare Workers
 *
 * Run with: node scripts/extract-bn128-wasm.js
 */

import { buildBn128 as buildBn128wasm } from "wasmcurves";
import { ModuleBuilder } from "wasmbuilder";
import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function extractBn128Wasm() {
    console.log("Building bn128 WASM module...");

    // Build the WASM module exactly as ffjavascript does
    const moduleBuilder = new ModuleBuilder();
    moduleBuilder.setMemory(25);
    buildBn128wasm(moduleBuilder);

    // Generate the WASM bytecode
    const wasmCode = moduleBuilder.build();

    console.log(`Generated WASM bytecode: ${wasmCode.length} bytes`);

    // Extract all the pointers and parameters we need
    const bn128Config = {
        pq: moduleBuilder.modules.f1m.pq,
        pr: moduleBuilder.modules.frm.pq,
        pG1gen: moduleBuilder.modules.bn128.pG1gen,
        pG1zero: moduleBuilder.modules.bn128.pG1zero,
        pG1b: moduleBuilder.modules.bn128.pG1b,
        pG2gen: moduleBuilder.modules.bn128.pG2gen,
        pG2zero: moduleBuilder.modules.bn128.pG2zero,
        pG2b: moduleBuilder.modules.bn128.pG2b,
        pOneT: moduleBuilder.modules.bn128.pOneT,
        prePSize: moduleBuilder.modules.bn128.prePSize,
        preQSize: moduleBuilder.modules.bn128.preQSize,
        n8q: 32,
        n8r: 32,
        q: moduleBuilder.modules.bn128.q.toString(),
        r: moduleBuilder.modules.bn128.r.toString(),
    };

    // Create output directory
    const outputDir = path.join(__dirname, "../src/workers/wasm");
    if (!fs.existsSync(outputDir)) {
        fs.mkdirSync(outputDir, { recursive: true });
    }

    // Write the WASM file
    const wasmPath = path.join(outputDir, "bn128.wasm");
    fs.writeFileSync(wasmPath, Buffer.from(wasmCode));
    console.log(`Written WASM to: ${wasmPath}`);

    // Write the config as a TypeScript module
    const configPath = path.join(outputDir, "bn128-config.ts");
    const configContent = `// Auto-generated bn128 configuration
// Generated by scripts/extract-bn128-wasm.js

export const bn128Config = ${JSON.stringify(bn128Config, null, 2)} as const;

// Field modulus q (bn128 base field)
export const q = BigInt("21888242871839275222246405745257275088696311157297823662689037894645226208583");

// Scalar field r (bn128 scalar field)
export const r = BigInt("21888242871839275222246405745257275088548364400416034343698204186575808495617");

// Cofactor for G2
export const cofactorG2 = BigInt("0x30644e72e131a029b85045b68181585e06ceecda572a2489345f2299c0f9fa8d");
`;
    fs.writeFileSync(configPath, configContent);
    console.log(`Written config to: ${configPath}`);

    console.log("\nDone! Now update rollup.config.js to include the WASM file.");
}

extractBn128Wasm().catch(console.error);

/**
 * Shared zero-knowledge types and circuit constants.
 *
 * Used by both the browser/server builds (where snarkjs handles proof generation
 * and verification) and the workers build (where verification runs through
 * `bn128.wasm` via `src/workers/groth16-verifier.ts`). Keeping these here ensures
 * proof shapes and verification keys stay identical across runtimes.
 */

/**
 * Groth16 proof structure (BN128).
 *
 * - `pi_a`: G1 point as `[x, y]` or projective `[x, y, z]`.
 * - `pi_b`: G2 point as `[[x0, x1], [y0, y1]]` or projective `[..., [z0, z1]]`.
 * - `pi_c`: G1 point as `[x, y]` or projective `[x, y, z]`.
 *
 * Field elements are decimal-string-encoded BigInts (snarkjs convention).
 */
export interface Groth16Proof {
  pi_a: string[];
  pi_b: string[][];
  pi_c: string[];
  protocol?: string;
  curve?: string;
}

/**
 * Groth16 verification key (BN128).
 *
 * Field elements are decimal-string-encoded BigInts (snarkjs convention).
 */
export interface VerificationKey {
  protocol: string;
  curve: string;
  nPublic: number;
  vk_alpha_1: string[];
  vk_beta_2: string[][];
  vk_gamma_2: string[][];
  vk_delta_2: string[][];
  vk_alphabeta_12: string[][][];
  IC: string[][];
}

